"""Demo bundle: the processed tables and trained models that the dashboards and the advisory bot need.

``data/sample/`` is tracked in git (everything else under ``data/`` and ``models/`` is regenerated by ``make pipeline``),
so a fresh clone, a Docker image or a Streamlit Cloud / Hugging Face Space can run the app without the multi-hour
IMD download. The bundle holds the *derived* district-level tables (not the raw gridded files), the three serving
models and the self-contained 3D simulator page, with a manifest of sizes and SHA-256 hashes.

* ``python -m config.bundle make``    copy the current pipeline outputs into ``data/sample`` and write the manifest;
* ``python -m config.bundle restore`` copy missing files back to ``data/processed``, ``models`` and ``simulator``
  (never overwrites; ``--force`` does) after verifying the hashes;
* ``python -m config.bundle verify``  check the bundle against its manifest.

The tables are derived district-level aggregates; the manifest note says whether the satellite table is real or synthetic
(flagged ``is_synthetic``). Check the
data licences in ``scripts/check_licenses.md`` before publishing the repository with the bundle.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import shutil
import sys
from datetime import UTC, datetime
from pathlib import Path

from config import ROOT

LOG = logging.getLogger(__name__)

BUNDLE = ROOT / "data" / "sample"
MANIFEST = BUNDLE / "MANIFEST.json"
# bundle sub-folder -> (destination relative to the repository root, file names)
LAYOUT: dict[str, tuple[str, tuple[str, ...]]] = {
    "processed": (
        "data/processed",
        (
            "districts.parquet",
            "weather_daily.parquet",
            "crops_annual.parquet",
            "satellite_16d.parquet",
            "district_clusters.parquet",
        ),
    ),
    "models": ("models", ("yield_xgb.joblib", "drought_xgb.joblib", "heatwave_lstm.pt")),
    "simulator": ("simulator", ("index_embedded.html", "sim_districts.json")),
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def entries() -> list[tuple[str, Path, Path]]:
    """``(relative name, bundle path, destination path)`` for every file of the layout."""
    items = []
    for folder, (destination, names) in LAYOUT.items():
        for name in names:
            items.append((f"{folder}/{name}", BUNDLE / folder / name, ROOT / destination / name))
    return items


def _note() -> str:
    """The manifest note, stating whether the bundled satellite table is synthetic (read from the bundled data)."""
    import pandas as pd

    base = "derived district-level tables and serving models; "
    try:
        satellite = pd.read_parquet(
            BUNDLE / "processed" / "satellite_16d.parquet", columns=["is_synthetic"]
        )
    except (
        Exception
    ) as exc:  # not a readable parquet table (for example a placeholder in a test layout)
        LOG.warning("satellite_16d provenance not read for the manifest note: %s", exc)
        return base + "satellite_16d provenance not checked"
    if bool(satellite["is_synthetic"].any()):
        return base + "satellite_16d is synthetic (is_synthetic=True)"
    return (
        base
        + "satellite_16d is real (MODIS NDVI and ERA5-Land soil moisture from Google Earth Engine)"
    )


def make() -> dict[str, dict[str, object]]:
    """Copy the pipeline outputs into the bundle and write ``MANIFEST.json``; raises if an output is missing."""
    missing = [str(dest) for _, _, dest in entries() if not dest.exists()]
    if missing:
        raise FileNotFoundError("run `make pipeline` first, missing: " + ", ".join(missing))
    files: dict[str, dict[str, object]] = {}
    for name, bundled, source in entries():
        bundled.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, bundled)
        files[name] = {"bytes": bundled.stat().st_size, "sha256": _sha256(bundled)}
    manifest = {
        "created": datetime.now(UTC).isoformat(timespec="seconds"),
        "note": _note(),
        "files": files,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    LOG.info(
        "bundled %d files (%.1f MB) into %s",
        len(files),
        sum(f["bytes"] for f in files.values()) / 1e6,
        BUNDLE,
    )
    return files


def verify() -> list[str]:
    """Names of bundle files that are missing or differ from the manifest (empty list = intact)."""
    if not MANIFEST.exists():
        return ["MANIFEST.json"]
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))["files"]
    problems = []
    for name, bundled, _ in entries():
        info = manifest.get(name)
        if info is None or not bundled.exists() or _sha256(bundled) != info["sha256"]:
            problems.append(name)
    return problems


def restore(force: bool = False) -> list[str]:
    """Copy bundle files to where the app expects them; returns the destinations written."""
    problems = verify()
    if problems:
        raise ValueError("bundle is incomplete or modified: " + ", ".join(problems))
    written = []
    for _, bundled, destination in entries():
        if destination.exists() and not force:
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(bundled, destination)
        written.append(str(destination.relative_to(ROOT)))
    if written:
        LOG.info("restored %d file(s) from the demo bundle", len(written))
    return written


def restore_if_missing() -> list[str]:
    """Quietly restore absent files when a valid bundle exists (used at app start-up); never raises."""
    if not MANIFEST.exists() or all(dest.exists() for _, _, dest in entries()):
        return []
    try:
        return restore()
    except (OSError, ValueError) as exc:
        LOG.warning("demo bundle not restored: %s", exc)
        return []


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(
        description="Create, verify or restore the demo bundle in data/sample."
    )
    parser.add_argument("action", choices=["make", "restore", "verify"])
    parser.add_argument("--force", action="store_true", help="restore: overwrite existing files")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    try:
        if args.action == "make":
            make()
        elif args.action == "restore":
            written = restore(args.force)
            LOG.info(
                "%s",
                f"wrote {len(written)} file(s)"
                if written
                else "nothing to do: all files already present",
            )
        else:
            problems = verify()
            LOG.info("%s", "bundle intact" if not problems else "problems: " + ", ".join(problems))
            return 1 if problems else 0
    except (FileNotFoundError, ValueError) as exc:
        LOG.error("%s", exc)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
