"""Farmer advisory: the SMS text the rule engine composes for a district, crop, date and language."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import pandas as pd
import streamlit as st

from config import load_settings
from dashboards.components import charts, data, guards, layout, models

LANGUAGES = {"en": "English", "hi": "हिन्दी (Hindi)", "ta": "தமிழ் (Tamil)", "te": "తెలుగు (Telugu)"}
MESSAGE_LABELS = {
    "heat_alert": "Heat alert",
    "drought_watch": "Drought watch",
    "irrigation_plan": "Irrigation plan",
    "sowing_window": "Sowing window",
    "all_clear": "All clear",
}


def main() -> None:
    district, crop = layout.start(
        "Advisory",
        needs=("processed data", "early-warning models", "yield models"),
        label="Farmers",
        intro="Fixed message templates driven by the early-warning level, the optimized irrigation plan and the crop calendar. No text is generated by a language model.",
    )
    first, last = models.risk_range()
    default = min(max(pd.Timestamp("2024-06-15"), first), last)
    with st.sidebar:
        lang = st.selectbox(
            "Language", list(LANGUAGES), format_func=LANGUAGES.get, key="advisory_lang"
        )
        as_of = st.date_input(
            "Advisory date", value=default.date(), min_value=first.date(), max_value=last.date()
        )
    stamp = pd.Timestamp(as_of).strftime("%Y-%m-%d")

    advisory = models.advisory(district, crop, stamp, lang)
    st.subheader("Message to the farmer")
    st.code(advisory.text, language=None, wrap_lines=True)
    limit = int(load_settings()["advisory"]["sms_max_chars"])
    cols = st.columns(4)
    cols[0].metric("Characters", f"{len(advisory.text)} / {limit}")
    cols[1].metric(
        "SMS parts",
        advisory.sms_segments,
        help="GSM-7 messages hold 160 characters per part, Unicode (Hindi, Tamil, Telugu) 70.",
    )
    cols[2].metric("Messages used", ", ".join(MESSAGE_LABELS[m] for m in advisory.messages))
    cols[3].metric("Overall risk", charts.LEVEL_LABEL[advisory.risk["level"]])
    if lang != "en":
        st.warning(
            "This translation is a draft. It has not been reviewed by a native speaker or an agronomist and must be reviewed before it is sent to farmers.",
            icon="🗣️",
        )
    st.download_button(
        "Download text",
        advisory.text,
        file_name=f"advisory_{district}_{crop}_{stamp}_{lang}.txt",
        mime="text/plain; charset=utf-8",
    )

    st.subheader("Why this message")
    levels = advisory.risk["levels"]
    reasons = [
        f"Heatwave level **{levels['heatwave']}** (14-day probability {advisory.risk['heatwave_p']:.1%}).",
        f"Drought level **{levels['drought']}** (next-month probability {advisory.risk['drought_p']:.1%}).",
    ]
    if advisory.weeks_into_season is not None:
        reasons.append(
            f"The {crop} season is in week {advisory.weeks_into_season + 1}; planned irrigation this week is {advisory.irrigation_mm if advisory.irrigation_mm is not None else 0:.0f} mm (optimized plan for a typical-rainfall year, not a forecast of this season)."
        )
    else:
        reasons.append(
            f"The {data.season_of(crop)} season for {crop} is not under way on this date."
        )
    reasons.extend(advisory.notes)
    st.markdown("\n".join(f"- {r}" for r in reasons))

    with st.expander("Same advisory in all languages"):
        for code, name in LANGUAGES.items():
            text = models.advisory(district, crop, stamp, code).text
            st.markdown(f"**{name}**")
            st.code(text, language=None, wrap_lines=True)


guards.run_guarded(main)
