"""List the licences of the installed dependencies from their package metadata (nothing is recalled from memory).

Reads ``requirements.lock`` for the package names, looks each up with ``importlib.metadata`` (``License-Expression``,
``License`` or a ``License ::`` classifier) and writes a Markdown table. Packages whose licence contains GPL, AGPL,
LGPL, MPL, EPL, CC-BY-NC or "unknown" are listed first as *needs a human look*.

Run: ``python scripts/list_licenses.py [--output docs/DEPENDENCY_LICENSES.md]``.
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = logging.getLogger("list_licenses")
REVIEW = re.compile(r"GPL|AGPL|LGPL|MPL|EPL|NC|unknown|proprietary", re.I)


def licence_of(name: str) -> str:
    """The best licence string the package metadata offers."""
    try:
        meta = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed"
    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()
    text = (meta.get("License") or "").strip()
    if text and len(text) < 80 and "\n" not in text:
        return text
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::")
    ]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    return "unknown (long licence text)" if text else "unknown"


def package_names(lock: Path) -> list[str]:
    """Package names of a ``name==version`` requirements file."""
    names = []
    for line in lock.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([A-Za-z0-9_.\-]+)==", line.strip())
        if match:
            names.append(match[1])
    return sorted(set(names), key=str.lower)


def table(names: list[str]) -> str:
    """Markdown with a review section and the full list."""
    rows = [
        (n, metadata.version(n) if licence_of(n) != "not installed" else "-", licence_of(n))
        for n in names
    ]
    review = [r for r in rows if REVIEW.search(r[2])]
    lines = [
        "# Dependency licences",
        "",
        "Generated by `scripts/list_licenses.py` from installed package metadata.",
        "",
    ]
    lines += [
        f"## Needs a human look ({len(review)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {licence} |" for n, v, licence in review] or ["| (none) | | |"]
    lines += [
        "",
        f"## All packages ({len(rows)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {licence} |" for n, v, licence in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lock", type=Path, default=ROOT / "requirements.lock")
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "DEPENDENCY_LICENSES.md")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    text = table(package_names(args.lock))
    args.output.write_text(text, encoding="utf-8")
    LOG.info("wrote %s", args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
