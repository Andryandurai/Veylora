"""Generate docs/FINDINGS.md from the Phase 3 result files. No number in the document is typed by hand.

Wording that depends on a result (rises / falls / no detectable effect) is chosen from the numbers
themselves, and the data-status banner at the top is derived from the data-quality files so that
synthetic inputs can never be hidden.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

import pandas as pd

from analytics import common
from config import ROOT, get_path

LOG = logging.getLogger(__name__)
ALPHA = 0.05


def pct(x: float, digits: int = 0) -> str:
    """Format a share as a percentage string."""
    return f"{100 * x:.{digits}f}%"


def effect_words(coef: float, p: float) -> str:
    """'is associated with higher/lower yield' or 'has no statistically detectable association'."""
    if p >= ALPHA:
        return "has no statistically detectable association with yield"
    return "is associated with higher yield" if coef > 0 else "is associated with lower yield"


def sig(p: float) -> str:
    """Compact p-value text."""
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


def load_json(path: Path) -> dict:
    """Read a JSON file or return an empty dict."""
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def data_banner(quality: dict, provenance: dict) -> list[str]:
    """First lines of the document: what is real and what is synthetic."""
    share = quality.get("synthetic_share", {})
    synthetic = {t: s for t, s in share.items() if s > 0}
    lines = []
    if synthetic:
        parts = ", ".join(f"`{t}` ({pct(s)} synthetic)" for t, s in synthetic.items())
        lines.append(
            f"> **SYNTHETIC DATA IN USE: {parts}.** Findings that depend on these tables are flagged below."
        )
    else:
        lines.append("> All input tables are real (no synthetic rows).")
    if provenance:
        rain = provenance.get("rain_mm", {})
        lines.append(
            f"> Weather sources (share of district-days for rain): IMD grid {pct(rain.get('imd', 0))}, "
            f"NASA POWER {pct(rain.get('nasa_power', 0))}, synthetic {pct(rain.get('synthetic', 0))}."
        )
    return lines


def build() -> str:
    """Assemble the markdown document."""
    rv = common.load_results("rainfall_variability")
    yt = common.load_results("yield_trends")
    df = common.load_results("drought_flood_frequency")
    co = common.load_results("correlations")
    rg = common.load_results("regression")
    cl = common.load_results("clustering")
    quality = load_json(get_path("reports") / "data_quality.json")
    provenance = load_json(get_path("data_interim") / "weather_provenance.json")
    synthetic_sat = bool(
        rg.get("satellite_features_synthetic") or co.get("satellite_features_synthetic")
    )

    lines = ["# Findings: climate, weather and crop yield in the study districts", ""]
    lines += data_banner(quality, provenance)
    lines += [
        "",
        "Generated by `python -m analytics.make_findings` from `reports/analytics/*.json`; every number comes from the "
        "PostgreSQL warehouse. Unit of analysis: yield-reporting district units (see `docs/DECISIONS.md` D-006).",
        "",
        "## Five most important findings",
        "",
    ]

    # 1. rainfall variability
    top = rv["top_cv_districts"][0]
    rho = rv["spearman_meanrain_vs_cv"]
    lines += [
        f"1. **Rainfall variability differs sharply between districts.** The coefficient of variation of "
        f"kharif rainfall averages {rv['kharif_cv_mean']:.2f} across {rv['n_districts']} districts "
        f"({rv['years'][0]}-{rv['years'][1]}), against {rv['rabi_cv_mean']:.2f} for rabi. The most variable district is "
        f"{top['district']} (CV {top['cv']:.2f}, mean {top['mean_rain_mm']:.0f} mm); the most stable is "
        f"{rv['lowest_cv_district']['district']} (CV {rv['lowest_cv_district']['cv']:.2f}). Across districts, mean rainfall and CV have "
        f"Spearman rho = {rho['rho']:.2f} ({sig(rho['p'])}). The driest regional years were "
        + ", ".join(
            f"{y['year']} ({y['share_districts_below_normal']:.0%} of districts below normal)"
            for y in rv["driest_regional_years"]
        )
        + ".",
    ]

    # 2. yield trends
    inc, dec = yt["n_significant_increasing"], yt["n_significant_decreasing"]
    best = yt["strongest_increasing"][0] if yt["strongest_increasing"] else None
    rice_rows = [s for s in yt["series"] if s["crop"] == "rice"]
    rice_sig = [s for s in rice_rows if s["mk_p"] < ALPHA and s["mk_trend"] == "increasing"]
    lines += [
        f"2. **Yield trends differ by crop and state.** Of {yt['n_series']} state-crop series "
        f"({yt['years'][0]}-{yt['years'][1]}, balanced district panels), {inc} show a significant increase and {dec} a significant decrease "
        f"(Mann-Kendall, p < {ALPHA}). Rice rises significantly in {len(rice_sig)} of {len(rice_rows)} states "
        + (
            "("
            + ", ".join(
                f"{s['state']} {s['slope_t_ha_per_year']:+.3f} t/ha/yr, {s['slope_pct_of_mean_per_year']:+.1f}%/yr"
                for s in rice_sig
            )
            + ")"
            if rice_sig
            else ""
        )
        + (
            f"; the steepest relative gain is {best['crop']} in {best['state']} ({best['slope_pct_of_mean_per_year']:+.1f}% of mean per year)."
            if best
            else "."
        ),
    ]

    # 3. drought
    kd = df["kharif_drought"]
    prone = kd["most_drought_prone"][0]
    lines += [
        f"3. **Kharif droughts (season rain < 75% of the district mean) hit about one season in {1 / kd['mean_frequency']:.0f}.** "
        f"Mean frequency is {pct(kd['mean_frequency'], 1)} of {df['n_seasons_per_district']} seasons; {prone['district']} is most exposed "
        f"({prone['events']} events, {pct(prone['frequency'])}). The worst regional years were "
        + ", ".join(
            f"{y['year']} ({pct(y['share_of_districts_in_drought'])} of districts)"
            for y in kd["worst_regional_years"]
        )
        + f". Under the strict flood-risk definition (> 125% of mean and >= 3 days > 100 mm of district-mean rain) there were only "
        f"{df['flood_risk_events_total']} events in {df['flood_risk_districts_affected']} districts, because district-area-mean rainfall rarely exceeds 100 mm/day.",
    ]

    # 4. weather -> yield
    raw, within = co["rice_rain_raw"], co["rice_rain_within"]
    m1_rain = rg["rice"]["M1_twoway_FE_weather"]["rain_100mm"]
    m1_tmax = rg["rice"]["M1_twoway_FE_weather"]["tmax_c"]
    m3_rain = rg["rice"]["M3_district_FE_trend_weather"]["rain_100mm"]
    m3_tmax = rg["rice"]["M3_district_FE_trend_weather"]["tmax_c"]
    flip = (raw["pearson"] < 0) != (within["pearson"] < 0)
    flip_note = (
        " The sign flips: wetter districts yield less rice, but a wetter year helps a given district "
        "(spatial confounding, so pooled correlations are misleading)."
        if flip
        else ""
    )
    lines += [
        f"4. **Pooled and within-district views of weather and yield can disagree.** Pooled across districts, rice yield and kharif "
        f"rainfall have Pearson r = {raw['pearson']:.2f} (95% cluster-bootstrap CI {raw['pearson_lo']:.2f} to {raw['pearson_hi']:.2f}); "
        f"within districts, after removing each district's level and trend, r = {within['pearson']:.2f} "
        f"({within['pearson_lo']:.2f} to {within['pearson_hi']:.2f})."
        + flip_note
        + f" In the two-way fixed-effects regression (district and year effects, district-clustered SEs, n = {m1_rain['n']}), "
        f"+100 mm of rainfall {effect_words(m1_rain['coef'], m1_rain['p'])} ({m1_rain['coef']:+.3f} t/ha, {sig(m1_rain['p'])}) and +1 C of mean Tmax "
        f"{effect_words(m1_tmax['coef'], m1_tmax['p'])} ({m1_tmax['coef']:+.3f} t/ha, {sig(m1_tmax['p'])}); "
        f"in the district-FE-plus-trend model Tmax is {m3_tmax['coef']:+.3f} t/ha ({sig(m3_tmax['p'])}) and rain {m3_rain['coef']:+.3f} t/ha ({sig(m3_rain['p'])}). "
        f"Rain and Tmax together add {pct(m1_rain['partial_r2_weather'], 1)} of R-squared beyond district and year effects"
        + (
            ", which sets a low ceiling for any weather-based yield forecast."
            if m1_rain["partial_r2_weather"] < 0.05
            else "."
        ),
    ]

    # 5. clusters
    clusters = sorted(cl["clusters"], key=lambda c: c["cluster_id"])
    lines += [
        f"5. **Districts fall into {cl['chosen_k']} climate groups** (KMeans, silhouette {cl['chosen_silhouette']:.2f}, features from years <= {cl['train_years_up_to']} only): "
        + "; ".join(
            f"{c['label']} ({c['n_districts']} districts, mean kharif rain {c['mean_rain_mm']:.0f} mm, e.g. {', '.join(c['example_districts'][:2])})"
            for c in clusters
        )
        + ".",
        "",
    ]

    # tables
    coef = pd.DataFrame(rg["coefficients"])
    rice = coef[(coef["crop"] == "rice")][
        [
            "model",
            "term",
            "coef",
            "se_cluster",
            "p",
            "pct_of_mean_yield_per_1sd_within",
            "vif_within",
        ]
    ]
    lines += [
        "## Rice: fixed-effects regression",
        "",
        common.markdown_table(
            rice.rename(
                columns={
                    "pct_of_mean_yield_per_1sd_within": "% of mean yield per 1 SD",
                    "se_cluster": "SE (cluster)",
                    "vif_within": "VIF (within)",
                }
            ),
            4,
        ),
        "",
    ]
    lines += [
        "Max within-FE VIF per model: "
        + ", ".join(f"{m} {v:.1f}" for m, v in rg["max_vif_within"].items())
        + ". "
        "Full tables: `reports/analytics/regression_coefficients.csv`, `correlations.csv`, `yield_trends_table.csv`.",
        "",
    ]
    lines += ["## Figures", ""]
    for name, desc in [
        ("rainfall_anomaly_heatmap", "kharif rainfall anomaly, districts x years"),
        ("rainfall_cv_kharif", "kharif rainfall variability map"),
        ("yield_trends", "state yield trends with Theil-Sen fits"),
        ("drought_flood_frequency", "drought and flood-risk frequency maps"),
        ("correlations_within", "within-district weather-yield correlations"),
        ("regression_residuals", "regression residuals"),
        ("clusters_map", "climate-vulnerability clusters"),
    ]:
        lines.append(f"- `reports/figures/{name}.png` (and `.html` where interactive): {desc}")
    lines += ["", "## Limitations", ""]
    moran = co["morans_i_district_mean_yield"]
    lines += [
        "- **Ecological fallacy and aggregation.** All relationships are between district-level averages. They describe districts, not farms or villages, and say nothing certain about individual farmers.",
        "- **District units are approximate.** Yields refer to ICRISAT's 1966 parent districts; our polygons are reconstructed from 2021 boundaries (D-006). Weather is averaged over those polygons.",
        "- **Spatial dependence.** District mean yields are spatially autocorrelated (Moran's I, k = 5 neighbours: "
        + ", ".join(f"{c} {v['I']:.2f} (p = {v['p_one_sided']:.3f})" for c, v in moran.items())
        + "), so the effective sample size is smaller than the number of districts and p-values are optimistic even with district-clustered errors.",
        "- **Association, not causation.** Fixed effects remove district levels and common year shocks, but not time-varying confounders such as irrigation expansion, varieties or prices.",
        "- **Year effects absorb regional weather.** Model M1 (year FE) identifies weather effects only from differences between districts within a year; M3 (district FE + trend) uses common year-to-year variation. Compare both.",
        "- **Season attribution.** ICRISAT gives annual crop totals; each crop is assigned to one season (D-007). Rice also grows in rabi, so 'kharif rice' is an annual average. Sugarcane values look like jaggery equivalent (D-007).",
        f"- **Source data errors.** {quality.get('rows', {}).get('crops_annual', 'n/a')} crop rows kept after dropping implausible ones (D-012; list in `docs/DATA_QUALITY.md`).",
        "- **Weather product.** Tmax/Tmin from IMD are 1-degree grids; NASA POWER is a ~0.5-degree reanalysis product. See provenance in `docs/DATA_QUALITY.md`.",
    ]
    if synthetic_sat:
        lines += [
            "- **SYNTHETIC satellite features.** NDVI and soil moisture are currently generated from rainfall (Google Earth Engine is not authenticated), so "
            "any NDVI or soil-moisture result (correlations, M2 terms, the NDVI-yield query) is circular and must not be read as independent evidence.",
        ]
    lines += [""]
    return "\n".join(lines)


def main() -> None:
    """CLI entry point: write docs/FINDINGS.md."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    text = build()
    path = ROOT / "docs" / "FINDINGS.md"
    path.write_text(text, encoding="utf-8")
    LOG.info("wrote %s (%d characters)", path, len(text))


if __name__ == "__main__":
    main()
